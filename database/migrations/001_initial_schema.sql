-- NoiseSensor - schema consolidado do estado atual do projeto.
-- Este arquivo substitui as antigas migrations 001, 002 e 003.
-- Em banco existente, os CREATE IF NOT EXISTS preservam tabelas e dados.

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    telegram_chat_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sensors (
    sensor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    latitude NUMERIC(9, 6) NOT NULL,
    longitude NUMERIC(9, 6) NOT NULL,
    region VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    user_id BIGINT,

    CONSTRAINT fk_sensors_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE SET NULL,

    CONSTRAINT chk_sensors_status
        CHECK (status IN ('active', 'inactive'))
);

CREATE TABLE IF NOT EXISTS sensors_readings (
    reading_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id BIGINT NOT NULL,
    read_timestamp TIMESTAMPTZ NOT NULL,
    noise_db NUMERIC(6, 2) NOT NULL,

    CONSTRAINT fk_readings_sensor
        FOREIGN KEY (sensor_id)
        REFERENCES sensors(sensor_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_readings_noise
        CHECK (noise_db >= 0 AND noise_db <= 200),

    CONSTRAINT uq_readings_sensor_timestamp
        UNIQUE (sensor_id, read_timestamp)
);

CREATE TABLE IF NOT EXISTS prediction_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_version VARCHAR(100) NOT NULL,
    run_timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS predictions (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    sensor_id BIGINT NOT NULL,
    target_timestamp TIMESTAMPTZ NOT NULL,
    horizon_hours INTEGER NOT NULL,
    predicted_noise_db NUMERIC(8, 3) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_predictions_run
        FOREIGN KEY (run_id)
        REFERENCES prediction_runs(run_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_predictions_sensor
        FOREIGN KEY (sensor_id)
        REFERENCES sensors(sensor_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_predictions_horizon
        CHECK (horizon_hours >= 1),

    CONSTRAINT chk_predictions_noise
        CHECK (predicted_noise_db >= 0 AND predicted_noise_db <= 200)
);

CREATE TABLE IF NOT EXISTS current_predictions (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    sensor_id BIGINT NOT NULL,
    target_timestamp TIMESTAMPTZ NOT NULL,
    horizon_hours INTEGER NOT NULL,
    predicted_noise_db NUMERIC(8, 3) NOT NULL,
    run_timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    model_version VARCHAR(100) NOT NULL,

    CONSTRAINT fk_current_predictions_run
        FOREIGN KEY (run_id)
        REFERENCES prediction_runs(run_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_current_predictions_sensor
        FOREIGN KEY (sensor_id)
        REFERENCES sensors(sensor_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_current_predictions_horizon
        CHECK (horizon_hours >= 1),

    CONSTRAINT chk_current_predictions_noise
        CHECK (predicted_noise_db >= 0 AND predicted_noise_db <= 200),

    CONSTRAINT uq_current_predictions_sensor_timestamp
        UNIQUE (sensor_id, target_timestamp)
);

CREATE TABLE IF NOT EXISTS sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    revoked_at TIMESTAMPTZ,

    CONSTRAINT fk_sessions_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS email_verification_tokens (
    verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    used_at TIMESTAMPTZ,

    CONSTRAINT fk_email_verification_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS sensor_alert_settings (
    sensor_id BIGINT PRIMARY KEY,
    threshold_db NUMERIC(6, 2) NOT NULL DEFAULT 70.00,
    trigger_duration_seconds INTEGER NOT NULL DEFAULT 30,
    recovery_duration_seconds INTEGER NOT NULL DEFAULT 15,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_alert_settings_sensor
        FOREIGN KEY (sensor_id)
        REFERENCES sensors(sensor_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_alert_settings_threshold
        CHECK (threshold_db > 0 AND threshold_db <= 200),

    CONSTRAINT chk_alert_settings_trigger_duration
        CHECK (trigger_duration_seconds >= 1),

    CONSTRAINT chk_alert_settings_recovery_duration
        CHECK (recovery_duration_seconds >= 1)
);

CREATE TABLE IF NOT EXISTS alerts (
    alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id BIGINT NOT NULL,
    threshold_db NUMERIC(6, 2) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    peak_noise_db NUMERIC(6, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_alerts_sensor
        FOREIGN KEY (sensor_id)
        REFERENCES sensors(sensor_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_alerts_threshold
        CHECK (threshold_db > 0 AND threshold_db <= 200),

    CONSTRAINT chk_alerts_peak
        CHECK (peak_noise_db >= 0 AND peak_noise_db <= 200),

    CONSTRAINT chk_alerts_dates
        CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE IF NOT EXISTS sensor_alert_states (
    sensor_id BIGINT PRIMARY KEY,
    state VARCHAR(20) NOT NULL DEFAULT 'normal',
    condition_started_at TIMESTAMPTZ,
    recovery_started_at TIMESTAMPTZ,
    current_alert_id BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_alert_states_sensor
        FOREIGN KEY (sensor_id)
        REFERENCES sensors(sensor_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_alert_states_current_alert
        FOREIGN KEY (current_alert_id)
        REFERENCES alerts(alert_id)
        ON DELETE SET NULL,

    CONSTRAINT chk_alert_states_state
        CHECK (state IN ('normal', 'pending_alert', 'alert', 'pending_recovery'))
);

CREATE INDEX IF NOT EXISTS idx_sensors_user_id
    ON sensors(user_id);

CREATE INDEX IF NOT EXISTS idx_sensors_status
    ON sensors(status);

CREATE INDEX IF NOT EXISTS idx_readings_sensor_timestamp
    ON sensors_readings(sensor_id, read_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_readings_timestamp
    ON sensors_readings(read_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_prediction_runs_timestamp
    ON prediction_runs(run_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_predictions_sensor_target
    ON predictions(sensor_id, target_timestamp);

CREATE INDEX IF NOT EXISTS idx_predictions_run_id
    ON predictions(run_id);

CREATE INDEX IF NOT EXISTS idx_current_predictions_sensor_target
    ON current_predictions(sensor_id, target_timestamp);

CREATE INDEX IF NOT EXISTS idx_sessions_user_id
    ON sessions(user_id);

CREATE INDEX IF NOT EXISTS idx_sessions_token_hash
    ON sessions(token_hash);

CREATE INDEX IF NOT EXISTS idx_email_verification_user_id
    ON email_verification_tokens(user_id);

CREATE INDEX IF NOT EXISTS idx_email_verification_token_hash
    ON email_verification_tokens(token_hash);

CREATE UNIQUE INDEX IF NOT EXISTS uq_alerts_active_sensor
    ON alerts(sensor_id)
    WHERE ended_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_alerts_sensor_started_at
    ON alerts(sensor_id, started_at DESC);

