-- Tokens temporários usados para vincular uma conta NoiseSensor ao Telegram.
CREATE TABLE IF NOT EXISTS telegram_link_tokens (
    link_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    used_at TIMESTAMPTZ,

    CONSTRAINT fk_telegram_link_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_telegram_link_user_id
    ON telegram_link_tokens(user_id);

CREATE INDEX IF NOT EXISTS idx_telegram_link_token_hash
    ON telegram_link_tokens(token_hash);

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_telegram_chat_id
    ON users(telegram_chat_id)
    WHERE telegram_chat_id IS NOT NULL;
