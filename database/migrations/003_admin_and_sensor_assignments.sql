-- NoiseSensor - administração e associação N:N entre usuários e sensores.
-- Execute com a aplicação parada.
-- A migração é transacional: se algum passo falhar, o PostgreSQL desfaz a operação.

BEGIN;

-- 1. Adiciona o cargo sem alterar os usuários existentes.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS role VARCHAR(20) DEFAULT 'user';

UPDATE users
SET role = 'user'
WHERE role IS NULL;

ALTER TABLE users
    ALTER COLUMN role SET DEFAULT 'user';

ALTER TABLE users
    ALTER COLUMN role SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'users'::regclass
          AND conname = 'chk_users_role'
    ) THEN
        ALTER TABLE users
            ADD CONSTRAINT chk_users_role
            CHECK (role IN ('user', 'admin'));
    END IF;
END $$;

-- 2. Cria a relação N:N. Um sensor pode pertencer a vários usuários
--    e um usuário pode possuir vários sensores.
CREATE TABLE IF NOT EXISTS sensor_users (
    sensor_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_sensor_users
        PRIMARY KEY (sensor_id, user_id),

    CONSTRAINT fk_sensor_users_sensor
        FOREIGN KEY (sensor_id)
        REFERENCES sensors(sensor_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_sensor_users_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);

-- 3. Copia os vínculos antigos 1:N sem duplicá-los.
--    O bloco existe para que a migration continue idempotente caso
--    seja executada novamente depois que a coluna antiga já tiver sido removida.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'sensors'
          AND column_name = 'user_id'
    ) THEN
        INSERT INTO sensor_users (sensor_id, user_id)
        SELECT sensor_id, user_id
        FROM sensors
        WHERE user_id IS NOT NULL
        ON CONFLICT (sensor_id, user_id) DO NOTHING;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_sensor_users_user_id
    ON sensor_users(user_id);

CREATE INDEX IF NOT EXISTS idx_sensor_users_sensor_id
    ON sensor_users(sensor_id);

-- 4. Histórico das ações feitas por administradores.
CREATE TABLE IF NOT EXISTS admin_audit_log (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id BIGINT NOT NULL,
    action VARCHAR(50) NOT NULL,
    target_user_id BIGINT,
    target_sensor_id BIGINT,
    details TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_admin_audit_admin
        FOREIGN KEY (admin_user_id)
        REFERENCES users(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_admin_audit_target_user
        FOREIGN KEY (target_user_id)
        REFERENCES users(user_id)
        ON DELETE SET NULL,

    CONSTRAINT fk_admin_audit_target_sensor
        FOREIGN KEY (target_sensor_id)
        REFERENCES sensors(sensor_id)
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_admin_audit_created_at
    ON admin_audit_log(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_admin_audit_target_user
    ON admin_audit_log(target_user_id);

CREATE INDEX IF NOT EXISTS idx_admin_audit_target_sensor
    ON admin_audit_log(target_sensor_id);

-- 5. A relação antiga sensors.user_id deixa de ser necessária.
--    Primeiro removemos sua FK e índice; depois removemos a coluna.
--    Os vínculos já foram copiados para sensor_users acima.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'sensors'
          AND column_name = 'user_id'
    ) THEN
        ALTER TABLE sensors
            DROP CONSTRAINT IF EXISTS fk_sensors_user;

        DROP INDEX IF EXISTS idx_sensors_user_id;

        ALTER TABLE sensors
            DROP COLUMN user_id;
    END IF;
END $$;

COMMIT;
